package com.doceflux.doceflux_api.finance.service;

import com.doceflux.doceflux_api.finance.domain.FinancialTransaction;
import com.doceflux.doceflux_api.finance.domain.TransactionType;
import com.doceflux.doceflux_api.finance.dto.CashFlowResponse;
import com.doceflux.doceflux_api.finance.dto.ExpenseRequest;
import com.doceflux.doceflux_api.finance.dto.IncomeRequest;
import com.doceflux.doceflux_api.finance.dto.UpdateTransactionRequest;
import com.doceflux.doceflux_api.finance.repository.FinancialTransactionRepository;
import com.doceflux.doceflux_api.order.repository.OrderRepository;
import com.doceflux.doceflux_api.shared.BusinessRuleException;
import com.doceflux.doceflux_api.shared.ResourceNotFoundException;
import com.doceflux.doceflux_api.finance.repository.FinancialTransactionSpecifications;
import org.springframework.data.domain.Sort;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.ZoneId;
import java.util.List;
import java.util.UUID;

@Service
public class FinanceService {

    private static final int MONEY_SCALE = 2;
    private static final int DESCRIPTION_MAX = 255;
    private static final ZoneId BUSINESS_ZONE = ZoneId.of("America/Sao_Paulo");

    private final FinancialTransactionRepository transactionRepository;
    private final OrderRepository orderRepository;

    public FinanceService(FinancialTransactionRepository transactionRepository, OrderRepository orderRepository) {
        this.transactionRepository = transactionRepository;
        this.orderRepository = orderRepository;
    }

    @Transactional
    public FinancialTransaction registerIncome(UUID storeId, IncomeRequest request) {
        if (request.orderId() != null && !orderRepository.existsByIdAndStoreId(request.orderId(), storeId)) {
            throw new ResourceNotFoundException("Pedido não encontrado: " + request.orderId());
        }
        return transactionRepository.save(FinancialTransaction.income(
                storeId,
                request.description().trim(), request.amount(), request.date(),
                normalizeCategory(request.category()), request.orderId()));
    }

    @Transactional
    public FinancialTransaction registerExpense(UUID storeId, ExpenseRequest request) {
        return transactionRepository.save(FinancialTransaction.expense(
                storeId,
                request.description().trim(), request.amount(), request.date(),
                normalizeCategory(request.category())));
    }

    @Transactional
    public void registerOrderRevenue(UUID storeId, UUID orderId, String customerName, BigDecimal amount) {
        if (transactionRepository.existsByStoreIdAndOrderIdAndAutoGeneratedTrue(storeId, orderId)) {
            return;
        }
        String description = "Pedido #" + orderId.toString().substring(0, 8) + " - " + customerName;
        transactionRepository.save(FinancialTransaction.orderRevenue(
                storeId, truncate(description), amount, LocalDate.now(BUSINESS_ZONE), orderId));
    }

    @Transactional
    public FinancialTransaction update(UUID id, UUID storeId, UpdateTransactionRequest request) {
        FinancialTransaction transaction = findById(id, storeId);
        transaction.update(request.description().trim(), request.amount(), request.date(),
                normalizeCategory(request.category()));
        return transaction;
    }

    @Transactional
    public void deleteByPeriod(UUID storeId, LocalDate startDate, LocalDate endDate) {
        if (startDate.isAfter(endDate)) {
            throw new BusinessRuleException("A data inicial não pode ser posterior à data final");
        }
        transactionRepository.deleteByStoreIdAndPeriod(storeId, startDate, endDate);
    }

    @Transactional(readOnly = true)
    public List<FinancialTransaction> findAll(UUID storeId, TransactionType type, UUID orderId,
                                              LocalDate startDate, LocalDate endDate) {
        if (startDate != null && endDate != null && startDate.isAfter(endDate)) {
            throw new BusinessRuleException("A data inicial não pode ser posterior à data final");
        }
        return transactionRepository.findAll(
                FinancialTransactionSpecifications.withFilters(storeId, type, orderId, startDate, endDate),
                Sort.by(Sort.Order.desc("transactionDate"), Sort.Order.desc("createdAt")));
    }

    @Transactional
    public void delete(UUID id, UUID storeId) {
        transactionRepository.delete(findById(id, storeId));
    }

    @Transactional(readOnly = true)
    public FinancialTransaction findById(UUID id, UUID storeId) {
        return transactionRepository.findByIdAndStoreId(id, storeId)
                .orElseThrow(() -> new ResourceNotFoundException("Movimentação não encontrada: " + id));
    }

    @Transactional(readOnly = true)
    public CashFlowResponse cashFlow(UUID storeId, LocalDate startDate, LocalDate endDate) {
        if (startDate.isAfter(endDate)) {
            throw new BusinessRuleException("A data inicial não pode ser posterior à data final");
        }
        BigDecimal totalIncome = totalOf(storeId, TransactionType.INCOME, startDate, endDate);
        BigDecimal totalExpense = totalOf(storeId, TransactionType.EXPENSE, startDate, endDate);
        return new CashFlowResponse(startDate, endDate, totalIncome, totalExpense,
                totalIncome.subtract(totalExpense));
    }

    private BigDecimal totalOf(UUID storeId, TransactionType type, LocalDate startDate, LocalDate endDate) {
        BigDecimal total = transactionRepository.sumAmountByStoreIdAndTypeAndPeriod(storeId, type, startDate, endDate);
        return (total == null ? BigDecimal.ZERO : total).setScale(MONEY_SCALE);
    }

    private String truncate(String text) {
        return text.length() <= DESCRIPTION_MAX ? text : text.substring(0, DESCRIPTION_MAX);
    }

    private String normalizeCategory(String category) {
        return category == null || category.isBlank() ? null : category.trim();
    }
}
